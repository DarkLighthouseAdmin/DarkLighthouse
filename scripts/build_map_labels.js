// Builds travel-log/app/map-labels.js: a label anchor for every map shape (the "pole of inaccessibility" of its biggest
// piece, so the name sits inside the country even for odd shapes like Croatia or Chile), plus area and bounding box
// used for label priority and the "jump to" zoom. Reads only maps.js (Natural Earth, public domain). Run: node scripts/build_map_labels.js
const fs = require("fs"), path = require("path");
const APP = path.join(__dirname, "..", "travel-log", "app");
const g = {}; new Function("self", fs.readFileSync(path.join(APP, "maps.js"), "utf8"))(g);
const MAPS = g.MLTL_MAPS;
function rings(d) {
  return d.split(/Z/i).map(s => s.trim()).filter(Boolean).map(s => (s.replace(/^M/, "").split("L")).map(p => p.split(",").map(Number)));
}
function area(r) { let a = 0; for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] * r[i][1] - r[i][0] * r[j][1]); return Math.abs(a) / 2; }
function inside(x, y, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const a = r[i], b = r[j]; if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) c = !c; } return c; }
function segDist(px, py, a, b) { let x = a[0], y = a[1], dx = b[0] - x, dy = b[1] - y; if (dx || dy) { const t = Math.max(0, Math.min(1, ((px - x) * dx + (py - y) * dy) / (dx * dx + dy * dy))); x += dx * t; y += dy * t; } dx = px - x; dy = py - y; return dx * dx + dy * dy; }
function sd(x, y, r) { let m = Infinity; for (let i = 0, j = r.length - 1; i < r.length; j = i++) m = Math.min(m, segDist(x, y, r[i], r[j])); return (inside(x, y, r) ? 1 : -1) * Math.sqrt(m); }
// polylabel (Mapbox's algorithm, written from scratch): grid cells refined until the best interior point is found.
function polylabel(r, prec) {
  let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
  r.forEach(p => { minx = Math.min(minx, p[0]); miny = Math.min(miny, p[1]); maxx = Math.max(maxx, p[0]); maxy = Math.max(maxy, p[1]); });
  const w = maxx - minx, h = maxy - miny, size = Math.min(w, h); if (!size) return [minx, miny];
  const cell = (x, y, s) => ({ x, y, s, d: sd(x, y, r), max: sd(x, y, r) + s * Math.SQRT2 });
  const q = []; for (let x = minx; x < maxx; x += size) for (let y = miny; y < maxy; y += size) q.push(cell(x + size / 2, y + size / 2, size / 2));
  let best = cell(minx + w / 2, miny + h / 2, 0);
  while (q.length) {
    q.sort((a, b) => a.max - b.max); const c = q.pop();
    if (c.d > best.d) best = c;
    if (c.max - best.d <= prec) continue;
    const s = c.s / 2; q.push(cell(c.x - s, c.y - s, s), cell(c.x + s, c.y - s, s), cell(c.x - s, c.y + s, s), cell(c.x + s, c.y + s, s));
  }
  return [best.x, best.y];
}
function build(shapes, prec) {
  const out = {};
  shapes.forEach(s => {
    const rs = rings(s.d).filter(r => r.length >= 3);
    let big = rs[0], A = 0, tot = 0; rs.forEach(r => { const a = area(r); tot += a; if (a > A) { A = a; big = r; } });
    let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
    // the bounding box used to zoom: the main piece plus any pieces nearby (skip far-flung islands, e.g. France's overseas parts)
    const bw0 = big ? Math.max(...big.map(p => p[0])) - Math.min(...big.map(p => p[0])) : 0;
    rs.forEach(r => { const a = area(r); const cx = r[0][0], ok = r === big || a > A * 0.25 || Math.abs(cx - big[0][0]) < Math.max(bw0 * 1.5, 6); if (!ok) return;
      r.forEach(p => { minx = Math.min(minx, p[0]); miny = Math.min(miny, p[1]); maxx = Math.max(maxx, p[0]); maxy = Math.max(maxy, p[1]); }); });
    const c = big && A > 0.05 ? polylabel(big, Math.max(Math.sqrt(A) / 40, 0.02)) : (s.c || [minx, miny]);
    const f = v => Math.round(v * 10) / 10;
    out[s.id] = [f(c[0]), f(c[1]), Math.round(tot * 100) / 100, f(minx), f(miny), f(maxx - minx), f(maxy - miny)];
  });
  return out;
}
const data = { world: build(MAPS.world.shapes), us: build(MAPS.us.shapes) };
fs.writeFileSync(path.join(APP, "map-labels.js"), "/* Generated by scripts/build_map_labels.js from maps.js (Natural Earth, public domain). [labelX, labelY, area, bboxX, bboxY, bboxW, bboxH] per shape. Do not edit by hand. */\n" +
  "(function (g) { g.MLTL_LABELS = " + JSON.stringify(data) + "; })(typeof self !== 'undefined' ? self : this);\n");
